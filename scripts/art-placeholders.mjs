// Writes tiny, softened copies of each scene and room painting to
// features/diorama/data/placeholders.ts. They are inlined into the page, so
// a scene can show a blurred version of itself on the very first frame and
// sharpen once the real layers are ready (see shared/art-veil.tsx). Re-run
// when a scene's or room's art changes:
//   node scripts/art-placeholders.mjs
import sharp from 'sharp';
import fs from 'node:fs/promises';

const art = 'public/assets/world';
const paintings = {
  // Home scenes use their static composite. The lake's sky is the journey's
  // own sky, so its horizon mask becomes the placeholder's alpha.
  lake: { src: 'lake-static-glasses-v1', mask: 'lake-horizon-mask-v1' },
  beach: { src: 'beach-static' },
  city: { src: 'city-static-glasses-v1' },
  work: { src: 'work-globe-room' },
  'work-portrait': { src: 'work-globe-room-portrait' },
  writing: { src: 'writing' },
  'writing-portrait': { src: 'writing-portrait-v1' },
};

const width = 48;
let ts = `// Generated by scripts/art-placeholders.mjs. Do not edit by hand.
/** Tiny softened copies of each painting, shown until the real art is ready. */
export const artPlaceholders = {
`;
for (const [name, { src, mask }] of Object.entries(paintings)) {
  const meta = await sharp(`${art}/${src}.webp`).metadata();
  const height = Math.round((width * meta.height) / meta.width);
  let image = sharp(`${art}/${src}.webp`).resize(width, height).removeAlpha();
  if (mask) {
    const alpha = await sharp(`${art}/${mask}.webp`)
      .resize(width, height)
      .extractChannel(3)
      .toBuffer();
    image = sharp(await image.toBuffer()).joinChannel(alpha);
  } else if (meta.hasAlpha) {
    image = sharp(`${art}/${src}.webp`).resize(width, height);
  }
  const data = await image
    .blur(0.8)
    .webp({ quality: 60, alphaQuality: 60 })
    .toBuffer();
  ts += `  '${name}': 'url("data:image/webp;base64,${data.toString('base64')}")',\n`;
  console.log(name, `${width}×${height}`, data.length, 'bytes');
}
ts += `} as const;\n`;
await fs.writeFile('features/diorama/data/placeholders.ts', ts);
