// Measures the Work room's painted monitor screen, in both the landscape and
// the portrait painting, straight from the approved artwork, and writes
// features/diorama/rooms/work/screen-mask.ts. The desktop then fills the whole
// painted screen, and whatever is painted in front of it (Glen's head on large
// screens, the laptop lid on phones) stays in front. Re-run if the art changes:
//   node scripts/work-screen-mask.mjs
import sharp from 'sharp';
import fs from 'node:fs/promises';

const paintings = {
  workScreen: {
    art: 'public/assets/world/work-globe-room.webp',
    seed: { x: 780, y: 300 },
    rows: [250, 300, 350, 400],
    topCols: [520, 700, 900, 1050],
    bottomCols: [500, 530, 1040, 1070],
  },
  workScreenPortrait: {
    art: 'public/assets/world/work-globe-room-portrait.webp',
    seed: { x: 400, y: 450 },
    rows: [350, 400, 450, 500],
    topCols: [200, 300, 500, 600],
    bottomCols: [150, 650, 700, 720],
  },
};
// The painted screen is a flat warm cream (#fef6e1 and neighbours).
const screenCream = [254, 246, 225];
// Extend the box under the bezel so no light seam shows at the edges.
const pad = 2;

async function measure({ art, seed, rows, topCols, bottomCols }) {
  const { data, info } = await sharp(art)
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: W, height: H, channels: C } = info;
  const rgb = (x, y) => {
    const i = (y * W + x) * C;
    return [data[i], data[i + 1], data[i + 2]];
  };
  const cream = (x, y) => {
    const [r, g, b] = rgb(x, y);
    return r >= 236 && g >= 228 && b >= 200 && r - b < 45;
  };

  // 1. The screen rectangle: walk out from a point known to be screen.
  const run = (x, y, dx, dy) => {
    while (cream(x + dx, y + dy)) {
      x += dx;
      y += dy;
    }
    return dx ? x : y;
  };
  const left = Math.max(...rows.map(y => run(seed.x, y, -1, 0)));
  const right = Math.min(...rows.map(y => run(seed.x, y, 1, 0)));
  const top = Math.max(...topCols.map(x => run(x, seed.y, 0, -1)));
  const bottom = Math.min(...bottomCols.map(x => run(x, seed.y, 0, 1)));

  // 2. The first row where something painted crosses the screen.
  let blockedFrom = bottom;
  for (let y = top; y <= bottom && blockedFrom === bottom; y++)
    for (let x = left + 6; x <= right - 6; x++)
      if (!cream(x, y)) {
        blockedFrom = y;
        break;
      }

  // 3. Alpha follows distance from the screen cream. Painted objects have a
  // dark outline, so blended edge pixels (cream half-mixed with that outline)
  // are covered too: left showing, they read as a pale line against the dark
  // desktop. The outline and the object itself stay in front.
  const coverage = (x, y) => {
    const [r, g, b] = rgb(x, y);
    const d = Math.hypot(
      r - screenCream[0],
      g - screenCream[1],
      b - screenCream[2],
    );
    return Math.max(0, Math.min(1, (220 - d) / 70));
  };
  const x0 = left - pad;
  const y0 = top - pad;
  const w = right - left + 1 + pad * 2;
  const h = bottom - top + 1 + pad * 2;
  const rgba = Buffer.alloc(w * h * 4, 255);
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const ax = x0 + x;
      const ay = y0 + y;
      if (ay < blockedFrom - 2) continue;
      // In the padding round the edge, an object crossing the edge stays in
      // front too; elsewhere the padding covers the bezel's inner line.
      const nx = Math.min(right, Math.max(left, ax));
      const ny = Math.min(bottom, Math.max(top, ay));
      const inScreen = nx === ax && ny === ay;
      if (inScreen || !cream(nx, ny))
        rgba[(y * w + x) * 4 + 3] = Math.round(coverage(ax, ay) * 255);
    }
  const png = await sharp(rgba, { raw: { width: w, height: h, channels: 4 } })
    .png({ compressionLevel: 9 })
    .toBuffer();
  const pct = (v, total) => +((v / total) * 100).toFixed(3);
  return {
    art,
    size: `${W}×${H}`,
    box: {
      left: pct(x0, W),
      top: pct(y0, H),
      width: pct(w, W),
      height: pct(h, H),
    },
    mask: `url("data:image/png;base64,${png.toString('base64')}")`,
    log: { left, right, top, bottom, blockedFrom, bytes: png.length },
  };
}

let ts = `// Generated by scripts/work-screen-mask.mjs from the Work room paintings.
// Do not edit by hand; re-run the script if the room art changes.
`;
for (const [name, painting] of Object.entries(paintings)) {
  const m = await measure(painting);
  console.log(name, m.log);
  const box = Object.entries(m.box)
    .map(([k, v]) => `  ${k}: ${v},`)
    .join('\n');
  ts += `
/** The painted monitor screen in ${m.art} (${m.size}), plus ${pad}px under the bezel, in percent of that painting. */
export const ${name} = {
${box}
} as const;

/** CSS mask for \`${name}\`: the whole screen, minus what is painted in front of it. */
export const ${name}Mask =
  '${m.mask}';
`;
}
await fs.writeFile('features/diorama/rooms/work/screen-mask.ts', ts);
