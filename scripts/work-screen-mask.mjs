// Measures the Work room's painted monitor screen and the outline of Glen's
// head in front of it, straight from the approved artwork, and writes
// features/diorama/rooms/work/screen-mask.ts. The desktop then fills the whole
// painted screen and passes behind his head. Re-run if the room art changes:
//   node scripts/work-screen-mask.mjs
import sharp from 'sharp';
import fs from 'node:fs/promises';

const art = 'public/assets/world/work-globe-room.webp';
const { data, info } = await sharp(art)
  .raw()
  .toBuffer({ resolveWithObject: true });
const { width: W, height: H, channels: C } = info;
const rgb = (x, y) => {
  const i = (y * W + x) * C;
  return [data[i], data[i + 1], data[i + 2]];
};
// The painted screen is a flat warm cream (#fef6e1 and neighbours).
const cream = (x, y) => {
  const [r, g, b] = rgb(x, y);
  return r >= 236 && g >= 230 && b >= 205 && r - b < 42;
};

// 1. The screen rectangle: walk out from a point known to be screen.
const seed = { x: 780, y: 300 };
const run = (x, y, dx, dy) => {
  while (cream(x + dx, y + dy)) {
    x += dx;
    y += dy;
  }
  return dx ? x : y;
};
const left = Math.max(...[250, 300, 350, 400].map(y => run(seed.x, y, -1, 0)));
const right = Math.min(...[250, 300, 350, 400].map(y => run(seed.x, y, 1, 0)));
const top = Math.max(...[520, 700, 900, 1050].map(x => run(x, seed.y, 0, -1)));
const bottom = Math.min(
  ...[500, 530, 1040, 1070].map(x => run(x, seed.y, 0, 1)),
);

// 2. A pixel mask over the screen, extended two pixels under the bezel so no
// light seam shows, hiding Glen's head from its first row down.
const pad = 2;
const x0 = left - pad;
const y0 = top - pad;
const w = right - left + 1 + pad * 2;
const h = bottom - top + 1 + pad * 2;
let headTop = bottom;
for (let y = top; y <= bottom && headTop === bottom; y++)
  for (let x = left + 6; x <= right - 6; x++)
    if (!cream(x, y)) {
      headTop = y;
      break;
    }
// Alpha follows the painting's own anti-aliasing: pure screen cream shows
// the desktop, the hair outline hides it, and edge pixels blend in between.
// Nothing is grown, so no painted cream halo or edge line is uncovered.
const screenCream = [254, 246, 225];
const creaminess = (x, y) => {
  const [r, g, b] = rgb(x, y);
  const d = Math.hypot(
    r - screenCream[0],
    g - screenCream[1],
    b - screenCream[2],
  );
  return Math.max(0, Math.min(1, (60 - d) / 50));
};
// Where the head crosses the screen's bottom edge, it stays in front of the
// few padding rows below too.
let headLeft = right;
let headRight = left;
for (let x = left + 6; x <= right - 6; x++)
  if (!cream(x, bottom)) {
    headLeft = Math.min(headLeft, x);
    headRight = Math.max(headRight, x);
  }
const rgba = Buffer.alloc(w * h * 4, 255);
for (let y = 0; y < h; y++)
  for (let x = 0; x < w; x++) {
    const ax = x0 + x;
    const ay = y0 + y;
    const inScreen = ax >= left && ax <= right && ay >= top && ay <= bottom;
    let alpha = 1;
    if (inScreen && ay >= headTop - 2) alpha = creaminess(ax, ay);
    else if (ay > bottom && ax >= headLeft - 2 && ax <= headRight + 2)
      alpha = creaminess(ax, ay);
    rgba[(y * w + x) * 4 + 3] = Math.round(alpha * 255);
  }
const png = await sharp(rgba, { raw: { width: w, height: h, channels: 4 } })
  .png({ compressionLevel: 9 })
  .toBuffer();
const pct = (v, total) => +((v / total) * 100).toFixed(3);

const ts = `// Generated by scripts/work-screen-mask.mjs from ${art} (${W}×${H}).
// Do not edit by hand; re-run the script if the room art changes.

/** The painted monitor screen (plus ${pad}px under the bezel), in percent of the room artwork. */
export const workScreen = {
  left: ${pct(x0, W)},
  top: ${pct(y0, H)},
  width: ${pct(w, W)},
  height: ${pct(h, H)},
} as const;

/** Where Glen's head starts, in percent of the screen box, for layout. */
export const workHeadTop = ${pct(headTop - y0, h)};

/** CSS mask: the whole screen, minus Glen's head in front of it. */
export const workScreenMask =
  'url("data:image/png;base64,${png.toString('base64')}")';
`;
await fs.writeFile('features/diorama/rooms/work/screen-mask.ts', ts);
console.log({ left, right, top, bottom, headTop, bytes: png.length });
